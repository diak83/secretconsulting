const calculateAge = (birthDateStr) => {
  if (!birthDateStr) return 20; // 기본값
  const birthYear = parseInt(birthDateStr.split("-")[0], 10);
  const currentYear = new Date().getFullYear();
  return currentYear - birthYear + 1; // 한국식 나이
};

